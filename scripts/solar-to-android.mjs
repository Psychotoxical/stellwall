// Turns the Solar icons the web app uses into Android vector drawables, so both look the same.
// Run from the repo root: node scripts/solar-to-android.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const ICONS = [
  "home-smile", "cart-large-2", "calendar", "chef-hat-minimalistic", "checklist-minimalistic", "menu-dots",
  "cake", "users-group-rounded", "user-rounded", "bell", "settings", "trash-bin-minimalistic", "notebook-bookmark", "document-text",
];
const set = JSON.parse(readFileSync("node_modules/@iconify-json/solar/icons.json", "utf8"));
const out = "android/app/src/main/res/drawable";
mkdirSync(out, { recursive: true });

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const strip = (a, names) => names.reduce((s, n) => s.replace(new RegExp(`\\s${n}="[^"]*"`), ""), a);

/** Shapes become paths; a group's opacity moves onto its children (vector drawables have no group alpha). */
function flatten(body) {
  return body
    .replace(/<g\b([^>]*)>([\s\S]*?)<\/g>/g, (_, g, inner) => {
      const o = attr(g, "opacity");
      return o ? inner.replace(/<(path|circle|ellipse)\b/g, `<$1 opacity="${o}"`) : inner;
    })
    .replace(/<circle\b([^>]*)\/>/g, (_, a) => {
      const [cx, cy, r] = ["cx", "cy", "r"].map((k) => Number(attr(a, k)));
      return `<path d="M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z"${strip(a, ["cx", "cy", "r"])}/>`;
    })
    .replace(/<ellipse\b([^>]*)\/>/g, (_, a) => {
      const [cx, cy, rx, ry] = ["cx", "cy", "rx", "ry"].map((k) => Number(attr(a, k)));
      return `<path d="M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z"${strip(a, ["cx", "cy", "rx", "ry"])}/>`;
    });
}

for (const name of ICONS) {
  const icon = set.icons[`${name}-bold-duotone`];
  if (!icon) throw new Error(`missing icon ${name}`);
  const flat = flatten(icon.body);
  if (/<(g|circle|rect|ellipse|polygon|line)\b/.test(flat)) throw new Error(`${name}: unsupported shape`);
  const paths = [...flat.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0]).map((tag) => {
    const d = attr(tag, "d");
    const opacity = attr(tag, "opacity");
    const evenOdd = attr(tag, "fill-rule") === "evenodd";
    return `    <path android:fillColor="#FF000000" android:pathData="${d}"${opacity ? ` android:fillAlpha="${opacity}"` : ""}${evenOdd ? ' android:fillType="evenOdd"' : ""} />`;
  });
  const w = icon.width ?? set.width ?? 24;
  const h = icon.height ?? set.height ?? 24;
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Solar by 480 Design, CC BY 4.0 (generated by scripts/solar-to-android.mjs) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="${w}" android:viewportHeight="${h}">
${paths.join("\n")}
</vector>
`;
  writeFileSync(`${out}/ic_${name.replace(/-/g, "_")}.xml`, xml);
}
console.log(`wrote ${ICONS.length} icons`);
